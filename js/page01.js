const form =
  document.getElementById("selvamForm");

const grid =
  document.getElementById("selvamGrid");

const totalEl =
  document.getElementById("totalScore");

const avgEl =
  document.getElementById("averageScore");

const statusEl =
  document.getElementById("formStatus");

const continueButton =
  document.getElementById("continueButton");

const STORAGE_KEY =
  "ctmPage01Assessment";

const NEXT_PAGE =
  "page02.html";


function render(){

  grid.innerHTML = SELVAMS.map(s => `

    <article
      class="selvam-card"
      data-selvam="${s.id}"
    >

      <div class="selvam-header">

        <div class="selvam-number">
          ${s.id}
        </div>

        <div>

          <div class="selvam-title-tamil">
            ${s.tamil}
          </div>

          <div class="selvam-title-english">
            ${s.english}
          </div>

        </div>

      </div>

      <p class="selvam-question-tamil">
        ${s.questionTamil}
      </p>

      <p class="selvam-question-english">
        ${s.questionEnglish}
      </p>

      <div class="rating-row">

        ${Array.from(
          {length:10},
          (_,i) => {

            const v = i + 1;
            const id =
              `selvam-${s.id}-${v}`;

            return `

              <div class="rating-option">

                <input
                  type="radio"
                  id="${id}"
                  name="selvam_${s.id}"
                  value="${v}"
                >

                <label for="${id}">
                  ${v}
                </label>

              </div>

            `;

          }
        ).join("")}

      </div>

      <div
        class="selected-value"
        id="selected-${s.id}"
      >
        உங்கள் மதிப்பீடு: ___ / 10
      </div>

    </article>

  `).join("");

  grid.addEventListener(
    "change",
    onChange
  );
}


function scores(){

  const out = {};

  SELVAMS.forEach(s => {

    const checked =
      document.querySelector(
        `input[name="selvam_${s.id}"]:checked`
      );

    out[s.id] =
      checked
        ? Number(checked.value)
        : null;

  });

  return out;
}


function average(x){

  const values =
    Object.values(x)
      .filter(n => n !== null);

  return values.length
    ? Number(
        (
          values.reduce(
            (a,b) => a + b,
            0
          ) / values.length
        ).toFixed(1)
      )
    : 0;
}


function update(){

  const s = scores();

  const values =
    Object.values(s)
      .filter(n => n !== null);

  const total =
    values.reduce(
      (a,b) => a + b,
      0
    );

  totalEl.textContent =
    total;

  avgEl.textContent =
    values.length
      ? (total / values.length).toFixed(1)
      : "0.0";
}


function draft(){

  const s = scores();

  const total =
    Object.values(s)
      .filter(n => n !== null)
      .reduce(
        (a,b) => a + b,
        0
      );

  localStorage.setItem(
    STORAGE_KEY,
    JSON.stringify({
      page:1,
      scores:s,
      totalScore:total,
      averageScore:average(s),
      savedAt:new Date().toISOString()
    })
  );
}


function onChange(e){

  if(
    !e.target.matches(
      'input[type="radio"]'
    )
  ){
    return;
  }

  const id =
    e.target.name.replace(
      "selvam_",
      ""
    );

  document
    .querySelector(
      `[data-selvam="${id}"]`
    )
    .classList.add("complete");

  document
    .getElementById(
      `selected-${id}`
    )
    .textContent =
      `உங்கள் மதிப்பீடு: ${e.target.value} / 10`;

  update();

  draft();
}


function restore(){

  const raw =
    localStorage.getItem(
      STORAGE_KEY
    );

  if(!raw){
    return;
  }

  try{

    const d =
      JSON.parse(raw);

    const s =
      d.scores || {};

    SELVAMS.forEach(x => {

      const v =
        s[x.id];

      if(!v){
        return;
      }

      const input =
        document.querySelector(
          `input[name="selvam_${x.id}"][value="${v}"]`
        );

      if(input){

        input.checked = true;

        document
          .querySelector(
            `[data-selvam="${x.id}"]`
          )
          .classList.add("complete");

        document
          .getElementById(
            `selected-${x.id}`
          )
          .textContent =
            `உங்கள் மதிப்பீடு: ${v} / 10`;
      }

    });

    update();

  }catch(e){

    console.warn(
      "Unable to restore Page 01 draft.",
      e
    );

  }
}


form.addEventListener(
  "submit",
  e => {

    e.preventDefault();

    const s = scores();

    const missing =
      SELVAMS.filter(
        x => s[x.id] === null
      );

    if(missing.length){

      statusEl.className =
        "form-status";

      statusEl.textContent =
        `Please rate all 16 Selvams before continuing. ${missing.length} remaining.`;

      document
        .querySelector(
          `[data-selvam="${missing[0].id}"]`
        )
        ?.scrollIntoView({
          behavior:"smooth",
          block:"center"
        });

      return;
    }

    const total =
      Object.values(s)
        .reduce(
          (a,b) => a + b,
          0
        );

    const avg =
      Number(
        (total / 16)
          .toFixed(1)
      );

    localStorage.setItem(
      STORAGE_KEY,
      JSON.stringify({
        page:1,
        scores:s,
        totalScore:total,
        averageScore:avg,
        completed:true,
        completedAt:
          new Date().toISOString()
      })
    );

    localStorage.setItem(
      "ctmPage01Complete",
      "true"
    );

    statusEl.className =
      "form-status success";

    statusEl.textContent =
      "உங்கள் மதிப்பீடு பாதுகாக்கப்பட்டது... Your assessment has been saved.";

    continueButton.disabled =
      true;

    setTimeout(
      () => {
        window.location.href =
          NEXT_PAGE;
      },
      500
    );

  }
);


render();
restore();
update();
